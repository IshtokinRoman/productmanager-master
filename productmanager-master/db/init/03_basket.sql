-- Корзина продуктов, собранная по плану питания

CREATE TABLE basket (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id     BIGINT NOT NULL,
    meal_plan_id BIGINT NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT fk_basket_owner
        FOREIGN KEY (owner_id) REFERENCES user_profile (id) ON DELETE CASCADE,
    CONSTRAINT fk_basket_meal_plan
        FOREIGN KEY (meal_plan_id) REFERENCES meal_plan (id) ON DELETE CASCADE,
    CONSTRAINT uq_basket_meal_plan UNIQUE (meal_plan_id)
);

CREATE INDEX idx_basket_owner ON basket (owner_id);

CREATE TABLE basket_item (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    basket_id  BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    amount     DOUBLE PRECISION NOT NULL,
    purchased  BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_basket_item_basket
        FOREIGN KEY (basket_id) REFERENCES basket (id) ON DELETE CASCADE,
    CONSTRAINT fk_basket_item_product
        FOREIGN KEY (product_id) REFERENCES product (id),
    CONSTRAINT uq_basket_item_basket_product UNIQUE (basket_id, product_id),
    CONSTRAINT chk_basket_item_amount CHECK (amount > 0)
);

CREATE INDEX idx_basket_item_product ON basket_item (product_id);
