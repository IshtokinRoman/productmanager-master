-- Семья: объединяет профили пользователей

CREATE TABLE family (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL
);

-- профиль состоит максимум в одной семье; при удалении семьи профили остаются без семьи
ALTER TABLE user_profile ADD COLUMN family_id BIGINT;
ALTER TABLE user_profile
    ADD CONSTRAINT fk_user_profile_family
        FOREIGN KEY (family_id) REFERENCES family (id) ON DELETE SET NULL;

CREATE INDEX idx_user_profile_family ON user_profile (family_id);
