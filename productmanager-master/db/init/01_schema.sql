-- Схема PostgreSQL для сущностей ru.productmanager.model
-- Имена таблиц и колонок соответствуют стандартной naming strategy Spring Boot (snake_case).
-- Положите файл в src/main/resources/db/migration/V1__init.sql (Flyway).

-- ---------------------------------------------------------------
-- product
-- ---------------------------------------------------------------
CREATE TABLE product (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(255) NOT NULL,
    category      VARCHAR(32),
    calories      DOUBLE PRECISION,
    protein       DOUBLE PRECISION,
    fat           DOUBLE PRECISION,
    carbohydrates DOUBLE PRECISION,
    CONSTRAINT chk_product_category CHECK (category IN (
        'MEAT', 'FISH', 'SEAFOOD', 'DAIRY', 'EGGS', 'GRAINS', 'PASTA', 'BREAD',
        'VEGETABLES', 'FRUITS', 'BERRIES', 'NUTS', 'LEGUMES', 'OIL', 'SAUCES',
        'SWEETS', 'BEVERAGES', 'OTHER')),
    CONSTRAINT chk_product_nutrients CHECK (
        COALESCE(calories, 0) >= 0 AND COALESCE(protein, 0) >= 0
        AND COALESCE(fat, 0) >= 0 AND COALESCE(carbohydrates, 0) >= 0)
);

-- уникальность без учёта регистра (под existsByNameIgnoreCase)
CREATE UNIQUE INDEX uq_product_name_lower ON product (lower(name));

-- ---------------------------------------------------------------
-- user_profile
-- ---------------------------------------------------------------
CREATE TABLE user_profile (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name     VARCHAR(100) NOT NULL,
    last_name      VARCHAR(100) NOT NULL,
    email          VARCHAR(255) NOT NULL,
    height         DOUBLE PRECISION,
    weight         DOUBLE PRECISION,
    birthday       DATE,
    gender         VARCHAR(16),
    activity_level VARCHAR(32),
    goal           VARCHAR(32),
    CONSTRAINT chk_user_profile_gender CHECK (gender IN ('MALE', 'FEMALE')),
    CONSTRAINT chk_user_profile_activity CHECK (
        activity_level IN ('LOW', 'MODERATE', 'HIGH', 'VERY_HIGH')),
    CONSTRAINT chk_user_profile_goal CHECK (
        goal IN ('WEIGHT_LOSS', 'MAINTENANCE', 'WEIGHT_GAIN')),
    CONSTRAINT chk_user_profile_body CHECK (
        COALESCE(height, 1) > 0 AND COALESCE(weight, 1) > 0)
);

-- уникальный email без учёта регистра
CREATE UNIQUE INDEX uq_user_profile_email_lower ON user_profile (lower(email));

-- ---------------------------------------------------------------
-- dish
-- ---------------------------------------------------------------
CREATE TABLE dish (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(255) NOT NULL,
    description  TEXT,
    cooking_time INTEGER,
    CONSTRAINT chk_dish_cooking_time CHECK (cooking_time IS NULL OR cooking_time > 0)
);

CREATE UNIQUE INDEX uq_dish_name_lower ON dish (lower(name));

-- ---------------------------------------------------------------
-- meal_type_by_dish: для каких приёмов пищи подходит блюдо (типов у блюда может быть несколько)
-- ---------------------------------------------------------------
CREATE TABLE meal_type_by_dish (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dish_id   BIGINT NOT NULL,
    meal_type VARCHAR(32) NOT NULL,
    CONSTRAINT fk_meal_type_by_dish_dish
        FOREIGN KEY (dish_id) REFERENCES dish (id) ON DELETE CASCADE,
    CONSTRAINT chk_meal_type_by_dish_type CHECK (meal_type IN (
        'BREAKFAST', 'LUNCH', 'DINNER', 'SNACK', 'SECOND_SNACK')),
    CONSTRAINT uq_meal_type_by_dish UNIQUE (dish_id, meal_type)
);

CREATE INDEX idx_meal_type_by_dish_type ON meal_type_by_dish (meal_type);

-- ---------------------------------------------------------------
-- dish_ingredient
-- (колонки calories нет: калорийность считается в коде, см. @Transient)
-- ---------------------------------------------------------------
CREATE TABLE dish_ingredient (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dish_id    BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    amount     DOUBLE PRECISION NOT NULL,
    CONSTRAINT fk_dish_ingredient_dish
        FOREIGN KEY (dish_id) REFERENCES dish (id) ON DELETE CASCADE,
    CONSTRAINT fk_dish_ingredient_product
        FOREIGN KEY (product_id) REFERENCES product (id),
    CONSTRAINT uq_dish_ingredient_dish_product UNIQUE (dish_id, product_id),
    CONSTRAINT chk_dish_ingredient_amount CHECK (amount > 0)
);

CREATE INDEX idx_dish_ingredient_product ON dish_ingredient (product_id);

-- ---------------------------------------------------------------
-- meal_plan
-- ---------------------------------------------------------------
CREATE TABLE meal_plan (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL,
    days     INTEGER NOT NULL,
    CONSTRAINT fk_meal_plan_owner
        FOREIGN KEY (owner_id) REFERENCES user_profile (id) ON DELETE CASCADE,
    CONSTRAINT chk_meal_plan_days CHECK (days >= 1)
);

CREATE INDEX idx_meal_plan_owner ON meal_plan (owner_id);

-- ---------------------------------------------------------------
-- meal
-- ---------------------------------------------------------------
CREATE TABLE meal (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dish_id      BIGINT NOT NULL,
    meal_plan_id BIGINT NOT NULL,
    day_number   INTEGER NOT NULL,
    meal_type    VARCHAR(32) NOT NULL,
    portion      DOUBLE PRECISION,
    CONSTRAINT fk_meal_dish
        FOREIGN KEY (dish_id) REFERENCES dish (id),
    CONSTRAINT fk_meal_meal_plan
        FOREIGN KEY (meal_plan_id) REFERENCES meal_plan (id) ON DELETE CASCADE,
    CONSTRAINT chk_meal_day_number CHECK (day_number >= 1),
    CONSTRAINT chk_meal_meal_type CHECK (meal_type IN (
        'BREAKFAST', 'LUNCH', 'DINNER', 'SNACK', 'SECOND_SNACK')),
    CONSTRAINT chk_meal_portion CHECK (portion IS NULL OR portion > 0)
);

CREATE INDEX idx_meal_meal_plan ON meal (meal_plan_id);
CREATE INDEX idx_meal_dish ON meal (dish_id);
