ALTER TABLE meal_plan ADD COLUMN family_id BIGINT;
ALTER TABLE meal_plan
    ADD CONSTRAINT fk_meal_plan_family
        FOREIGN KEY (family_id) REFERENCES family (id) ON DELETE SET NULL;

-- meal.portion хранит сумму порций всех участников, а здесь порция каждого участника отдельно
CREATE TABLE meal_portion (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meal_id   BIGINT NOT NULL,
    member_id BIGINT NOT NULL,
    portion   DOUBLE PRECISION NOT NULL,
    CONSTRAINT fk_meal_portion_meal
        FOREIGN KEY (meal_id) REFERENCES meal (id) ON DELETE CASCADE,
    CONSTRAINT fk_meal_portion_member
        FOREIGN KEY (member_id) REFERENCES user_profile (id) ON DELETE CASCADE,
    CONSTRAINT uq_meal_portion UNIQUE (meal_id, member_id),
    CONSTRAINT chk_meal_portion_value CHECK (portion > 0)
);

CREATE INDEX idx_meal_portion_member ON meal_portion (member_id);
